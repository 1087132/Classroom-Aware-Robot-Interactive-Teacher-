"""Constrained LLM / NLU module.

Answers short, on-topic student questions using ONLY the teacher-approved
lesson knowledge base, and politely refuses anything off-topic. This mirrors
the capstone design: a constrained model that reduces hallucination risk and
keeps the teacher in control.

Two layers:
  1. Retrieval NLU (TF-IDF style, zero dependencies) decides ON-TOPIC vs
     OFF-TOPIC and finds the approved fact. Off-topic never reaches the LLM.
  2. Local LLM generation (offline): if an Ollama server is running on this
     machine with a downloaded model (auto-detected, or forced via the
     OLLAMA_MODEL env var), the approved fact + question are passed to it for
     a natural, child-friendly answer. The model file lives on local disk
     (~/.ollama/models), so after the one-time download it works with NO
     internet connection. If the LLM is unavailable, the KB answer is used.
"""
import json
import math
import os
import re
import time
import urllib.request
from collections import Counter

OLLAMA_URL = os.environ.get("OLLAMA_URL", "http://127.0.0.1:11434")
PREFERRED_MODELS = ("llama3.2:3b", "llama3.2:1b", "llama3.2", "qwen2.5:1.5b", "gemma2:2b", "phi3")

STOPWORDS = set("""a an and are as at be but by can could did do does for from had has have how i if in
is it its of on or so that the their them then there these they this to was we what when where which
who why will with you your me my am us our tell about please explain""".split())

REFUSALS = [
    "Hmm, that question is outside today's lesson. Let's stay focused - try asking me about {topic}!",
    "Good curiosity! But I can only answer questions about {topic} right now. Ask your teacher after class!",
    "That's off-topic for this lesson. I'm here to help with {topic} today!",
]

SMALL_TALK = {
    "hello": "Hello there! Ready to learn something awesome today?",
    "hi": "Hi! I'm CAT, your classroom robot. Ask me about today's lesson!",
    "hey": "Hey! Let's learn together!",
    "thank": "You're very welcome! Keep those great questions coming!",
    "thanks": "Anytime! Learning together is fun!",
    "who are you": "I'm CAT - the Classroom-Aware Teacher robot! I help your teacher make lessons fun.",
    "what is your name": "My name is CAT - Classroom-Aware Teacher robot!",
    "how are you": "I'm charged up and excited to learn with you!",
}


def _tokens(text: str) -> list:
    words = re.findall(r"[a-z0-9]+", text.lower())
    return [w for w in words if w not in STOPWORDS and len(w) > 1]


class ConstrainedLLM:
    """Retrieval-based NLU restricted to a per-lesson knowledge base."""

    def __init__(self):
        self.topic = "today's lesson"
        self.kb = []          # list of {q, a, keywords}
        self.kb_docs = []     # tokenized docs
        self.idf = {}
        self._refusal_i = 0
        self.model = None             # active local LLM model name (None = retrieval only)
        self._model_checked = 0.0
        self.llm_used = 0             # answers generated by the local LLM
        self.detect_local_model()

    # ---------------- local offline LLM detection ----------------
    def detect_local_model(self):
        """Find a downloaded model on the local Ollama server (cached 30 s)."""
        if time.time() - self._model_checked < 30:
            return self.model
        self._model_checked = time.time()
        forced = os.environ.get("OLLAMA_MODEL")
        try:
            with urllib.request.urlopen(OLLAMA_URL + "/api/tags", timeout=2) as resp:
                tags = [m["name"] for m in json.loads(resp.read()).get("models", [])]
        except Exception:
            self.model = None
            return None
        if forced and any(t == forced or t.startswith(forced) for t in tags):
            self.model = next(t for t in tags if t == forced or t.startswith(forced))
        else:
            self.model = next((t for p in PREFERRED_MODELS for t in tags
                               if t == p or t.startswith(p + ":") or t.startswith(p)), 
                              tags[0] if tags else None)
        return self.model

    def status(self) -> dict:
        self.detect_local_model()
        return {
            "mode": "local-llm" if self.model else "retrieval",
            "model": self.model,
            "offline": True,
            "kb_facts": len(self.kb),
            "llm_answers": self.llm_used,
        }

    def load_lesson(self, lesson: dict) -> None:
        self.topic = lesson.get("topic_label", lesson.get("title", "today's lesson"))
        self.kb = list(lesson.get("knowledge_base", []))
        # Question text + explanations also become retrievable knowledge.
        for q in lesson.get("questions", []):
            if q.get("explanation"):
                self.kb.append({
                    "q": q["text"],
                    "a": q["explanation"],
                    "keywords": q.get("keywords", []),
                })
        self.kb_docs = [
            _tokens(item["q"]) + _tokens(" ".join(item.get("keywords", []))) + _tokens(item["a"])
            for item in self.kb
        ]
        n = len(self.kb_docs) or 1
        df = Counter()
        for doc in self.kb_docs:
            for w in set(doc):
                df[w] += 1
        self.idf = {w: math.log((1 + n) / (1 + c)) + 1.0 for w, c in df.items()}

    def _vec(self, tokens: list) -> dict:
        tf = Counter(tokens)
        return {w: (1 + math.log(c)) * self.idf.get(w, 1.5) for w, c in tf.items()}

    @staticmethod
    def _cosine(v1: dict, v2: dict) -> float:
        common = set(v1) & set(v2)
        num = sum(v1[w] * v2[w] for w in common)
        den = math.sqrt(sum(x * x for x in v1.values())) * math.sqrt(sum(x * x for x in v2.values()))
        return num / den if den else 0.0

    def answer(self, question: str) -> dict:
        """Return {'answer': str, 'on_topic': bool, 'matched': str|None, 'confidence': float}."""
        q_clean = question.strip().lower()
        q_words = set(re.findall(r"[a-z]+", q_clean))
        for key, reply in SMALL_TALK.items():
            hit = (key in q_clean) if " " in key else (key in q_words)   # word-boundary match
            if hit and len(q_clean) < 40:
                return {"answer": reply, "on_topic": True, "matched": "small_talk",
                        "confidence": 1.0, "source": "small_talk"}

        q_tokens = _tokens(question)
        if not q_tokens or not self.kb:
            return self._refuse()

        best_i, best_score = self._best_match(q_tokens)
        if best_i < 0 or best_score < 0.30:
            return self._refuse()

        item = self.kb[best_i]
        generated = self._maybe_ollama(question, item)
        return {"answer": generated or item["a"], "on_topic": True, "matched": item["q"],
                "confidence": round(min(best_score, 1.0), 2),
                "source": self.model if generated else "knowledge-base"}

    def _best_match(self, q_tokens: list):
        """Best knowledge-base match for a token list -> (index, score)."""
        q_vec = self._vec(q_tokens)
        best_i, best_score = -1, 0.0
        for i, doc in enumerate(self.kb_docs):
            score = self._cosine(q_vec, self._vec(doc))
            # keyword boost: explicit lesson keywords are strong on-topic signals
            kw = set(_tokens(" ".join(self.kb[i].get("keywords", []))))
            overlap = len(kw & set(q_tokens))
            score += 0.15 * min(overlap, 2)
            if score > best_score:
                best_i, best_score = i, score
        return best_i, best_score

    def _refuse(self) -> dict:
        msg = REFUSALS[self._refusal_i % len(REFUSALS)].format(topic=self.topic)
        self._refusal_i += 1
        return {"answer": msg, "on_topic": False, "matched": None, "confidence": 0.0}

    # ---------------- speech-to-text interaction classification ----------------
    QUESTION_STARTERS = ("what", "why", "how", "when", "where", "which", "who",
                         "can", "could", "does", "do", "is", "are", "will")

    def classify_interaction(self, transcript: str, current_options=None) -> dict:
        """Classify a spoken utterance captured by STT.

        Returns {'interaction': bool, 'kind': 'answer'|'question'|'comment'|'chatter',
                 'confidence': float, 'option': int|None}.
        'interaction' = the student is engaging with the teacher/lesson.
        """
        t = re.sub(r"\s+", " ", (transcript or "")).strip()
        if not t:
            return {"interaction": False, "kind": "silence", "confidence": 0.0, "option": None}
        tl = t.lower()

        # spoken answer to the OPEN question? (matches one of its options)
        if current_options:
            for i, opt in enumerate(current_options):
                ol = str(opt).lower().strip()
                if ol and (ol in tl or tl in ol):
                    return {"interaction": True, "kind": "answer",
                            "confidence": 0.9, "option": i}

        words = tl.split()
        is_question = t.endswith("?") or (words and words[0] in self.QUESTION_STARTERS)
        addressed = any(w in words for w in ("teacher", "miss", "sir", "cat", "robot"))

        tokens = _tokens(t)
        _i, score = self._best_match(tokens) if tokens and self.kb else (-1, 0.0)
        # questions engage easily; plain statements need stronger topical evidence
        if score >= (0.30 if is_question else 0.50):
            return {"interaction": True, "kind": "question" if is_question else "comment",
                    "confidence": round(min(score, 1.0), 2), "option": None}
        if is_question or addressed:            # engaging, even if loosely on-topic
            return {"interaction": True, "kind": "question" if is_question else "comment",
                    "confidence": 0.4, "option": None}
        return {"interaction": False, "kind": "chatter",
                "confidence": round(score, 2), "option": None}

    def _generate(self, prompt: str, num_predict=70, temperature=0.4):
        """Core call to the LOCAL model. Returns clean text or None (offline-safe)."""
        model = self.detect_local_model()
        if not model:
            return None
        try:
            body = json.dumps({
                "model": model, "prompt": prompt, "stream": False,
                "options": {"temperature": temperature, "num_predict": num_predict},
            }).encode()
            req = urllib.request.Request(OLLAMA_URL + "/api/generate", data=body,
                                         headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=25) as resp:
                text = json.loads(resp.read())["response"].strip()
            return re.sub(r"\s+", " ", text).strip('"')
        except Exception:
            return None  # graceful fallback (still fully offline)

    def _maybe_ollama(self, question: str, item: dict):
        """Generate an answer constrained to the approved lesson fact."""
        text = self._generate(
            "You are CAT, a friendly classroom robot for children. Answer the student's "
            "question in ONE short, cheerful sentence using ONLY this approved lesson "
            "fact. Do not add outside information, do not use emojis.\n"
            f"Approved fact: {item['a']}\n"
            f"Student question: {question}\n"
            "Answer:")
        if text and 3 <= len(text) <= 300:
            self.llm_used += 1
            return text
        return None

    # ---------------- MCQ integration ----------------
    def answer_feedback(self, qtext, options, chosen_idx, correct_idx, explanation, correct):
        """One personalized sentence about THIS student's MCQ answer."""
        situation = (
            f"The student answered '{options[chosen_idx]}' which is CORRECT."
            if correct else
            f"The student answered '{options[chosen_idx]}' but the correct answer is "
            f"'{options[correct_idx]}'."
        )
        text = self._generate(
            "You are CAT, a friendly classroom robot for children. A student just answered "
            "a quiz question. Reply with ONE short, kind sentence of feedback for that "
            "student. No emojis, no lists.\n"
            f"Question: {qtext}\n{situation}\n"
            f"Approved explanation: {explanation}\n"
            "Feedback:", num_predict=50)
        if text and 3 <= len(text) <= 250:
            self.llm_used += 1
            return text
        return None

    def review_comment(self, qtext, options, distribution, correct_idx, n_correct, n_total):
        """One classroom-wide insight after an MCQ closes, from the answer distribution."""
        if not n_total:
            return None
        picks = ", ".join(f"'{options[i]}': {c} students"
                          for i, c in enumerate(distribution) if c > 0)
        text = self._generate(
            "You are CAT, a friendly classroom robot. A quiz question just finished. "
            "Say ONE short encouraging sentence to the whole class about the results. "
            "No emojis.\n"
            f"Question: {qtext}\n"
            f"Correct answer: '{options[correct_idx]}'. {n_correct} of {n_total} students "
            f"answered correctly. Answers given: {picks}.\n"
            "Comment:", num_predict=50)
        if text and 3 <= len(text) <= 250:
            self.llm_used += 1
            return text
        return None

    def distill_fact(self, passage: str):
        """Extract ONE self-contained, teachable fact from a textbook passage.
        Returns None if the passage is just exercises/context-bound content."""
        text = self._generate(
            "From this textbook passage, write ONE short self-contained fact that a "
            "child should learn. It must make sense on its own - no names of people, "
            "no references to pictures, pages or exercises. If the passage has no such "
            "fact, reply exactly: NONE\n"
            f"Passage: {passage[:400]}\n"
            "Fact:", num_predict=60, temperature=0.3)
        if not text or text.lower().startswith("none") or len(text) < 25 or len(text) > 220:
            return None
        # person names / titles mid-sentence = exercise-bound content, not a fact
        if re.search(r"(?<!^)\b[A-Z][a-z]{2,}\b", text.replace("Celsius", "c").replace("Fahrenheit", "f")):
            return None
        # grounding: most content words must come from the passage itself
        toks = _tokens(text)
        if not toks:
            return None
        pl = passage.lower()
        hit = sum(1 for t in toks if t in pl)
        if hit / len(toks) < 0.6:
            return None
        return text

    def generate_mcq(self, fact=None):
        """Create ONE new MCQ from the teacher-approved knowledge base (or a
        given textbook passage).

        The model names the correct answer EXPLICITLY (not by index) and we
        shuffle the options ourselves - far more reliable with small models.
        """
        if not self.detect_local_model() or not (fact or self.kb):
            return None
        import random as _random
        if fact is None:
            fact = _random.choice(self.kb)
        if isinstance(fact, str):
            fact = {"a": fact}
        for _attempt in range(4):
            raw = self._generate(
                "You write one short quiz question for children, based ONLY on the fact.\n"
                "Return ONLY a JSON object, no markdown. Follow the example style exactly.\n\n"
                "Example fact: Water freezes at 0 degrees Celsius.\n"
                'Example JSON: {"text": "At what temperature does water freeze?", '
                '"correct": "0 degrees Celsius", "wrong": ["100 degrees Celsius", '
                '"37 degrees Celsius", "10 degrees Celsius"], '
                '"explanation": "Water turns to ice at 0 degrees Celsius."}\n\n'
                f"Fact: {fact['a']}\n"
                "Rules: the text must be a real question ending with '?'. The question must "
                "NOT contain the correct answer. The correct answer must be true according "
                "to the fact. Wrong answers must clearly be incorrect.\nJSON:",
                num_predict=200, temperature=0.6)
            if not raw:
                return None
            m = re.search(r"\{.*\}", raw, re.S)
            if not m:
                continue
            try:
                q = json.loads(m.group(0))
                text = str(q.get("text", "")).strip()
                correct = str(q.get("correct", "")).strip()
                c_digits = "".join(re.findall(r"\d", correct))
                wrong = [str(w).strip() for w in q.get("wrong", [])
                         if str(w).strip() and str(w).strip().lower() != correct.lower()
                         and len(str(w).strip()) <= 80
                         and not re.fullmatch(r"[a-fA-F]", str(w).strip())
                         and not (c_digits and "".join(re.findall(r"\d", str(w))) == c_digits)]
                wrong = list(dict.fromkeys(wrong))[:3]      # no duplicate options
                # reject 'statement echo' questions (correct option ~= the question)
                if len(correct) > 20:
                    ct, tt = set(_tokens(correct)), set(_tokens(text))
                    if ct and len(ct & tt) / len(ct) > 0.7:
                        continue
                if re.fullmatch(r"[a-fA-F]", correct):     # bare letters = workbook refs
                    continue
                # quality gates for small models
                if (len(text) < 10 or "?" not in text or not correct or len(wrong) < 2
                        or len(correct) > 80
                        or "the question" in text.lower()
                        or (len(correct) >= 3 and correct.lower() in text.lower())):
                    continue
                # grounding gate: the correct answer must come FROM the fact itself
                fact_l = fact["a"].lower()
                c_tokens = _tokens(correct) or [correct.lower()]
                grounded = (correct.lower() in fact_l
                            or all(t in fact_l for t in c_tokens))
                if not grounded:
                    continue
                # numeric sanity: 'largest/smallest' questions must be arithmetically right
                if all(re.fullmatch(r"-?\d+(\.\d+)?", o) for o in [correct] + wrong):
                    vals = [float(o) for o in [correct] + wrong]
                    tl2 = text.lower()
                    if re.search(r"\b(largest|biggest|greatest|highest)\b", tl2) and float(correct) != max(vals):
                        continue
                    if re.search(r"\b(smallest|least|lowest|littlest)\b", tl2) and float(correct) != min(vals):
                        continue
                options = [correct] + wrong
                _random.shuffle(options)
                self.llm_used += 1
                return {"text": text, "options": options, "answer": options.index(correct),
                        "explanation": (str(q.get("explanation", "")).strip()
                                        or fact["a"])[:200],
                        "based_on": fact["a"][:120]}
            except (ValueError, TypeError, json.JSONDecodeError):
                continue
        return None
